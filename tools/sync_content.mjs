// Regenerates CONTENT.md, a plain mirror of the text the site renders from
// src/data. Run from the repo root:  node tools/sync_content.mjs
// Copy that lives inside components (hero summary, profile paragraphs, the
// studio block) is listed by file at the end rather than duplicated here.
import { build } from 'esbuild';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const out = join(mkdtempSync(join(tmpdir(), 'content-')), 'data.mjs');
await build({
  stdin: {
    contents: [
      "export { profile } from './src/data/profile.ts';",
      "export { heroStats } from './src/data/stats.ts';",
      "export { marqueeTokens } from './src/data/marquee.ts';",
      "export { experience } from './src/data/experience.ts';",
      "export { work } from './src/data/work.ts';",
      "export { games } from './src/data/games.ts';",
      "export { bento } from './src/data/expertise.ts';",
      "export { contactDetails, socials } from './src/data/contact.ts';",
      "export { navLinks } from './src/data/navigation.ts';",
    ].join('\n'),
    resolveDir: process.cwd(),
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  outfile: out,
  logLevel: 'silent',
});
const d = await import(pathToFileURL(out).href);
const today = new Date().toISOString().slice(0, 10);
const L = [];
const h = (text) => L.push('', `## ${text}`, '');

L.push(
  '# Portfolio content',
  '',
  'Everything the site renders from `src/data`, top to bottom. Generated by',
  '`tools/sync_content.mjs`; edit the data files, then run the script. Do not edit this file by hand.',
  '',
  `_Generated ${today}._`,
);

h('Identity (`src/data/profile.ts`)');
for (const [key, value] of Object.entries(d.profile)) L.push(`- **${key}:** ${value}`);

h('Navigation (`src/data/navigation.ts`)');
L.push(d.navLinks.map((link) => `${link.label} (${link.href})`).join(' · '));

h('Stats band (`src/data/stats.ts`)');
for (const stat of d.heroStats) L.push(`- **${stat.value}${stat.suffix ?? ''}** ${stat.label}`);

h('Marquee (`src/data/marquee.ts`)');
L.push(d.marqueeTokens.filter((token) => token.kind === 'word').map((token) => token.text).join(' ✦ '));

h('Career arc (`src/data/experience.ts`)');
for (const entry of d.experience) {
  L.push(`### ${entry.role}`, `${entry.org} · ${entry.period}`, '', entry.description, '');
  L.push(`Tags: ${entry.tags.join(', ')}`, '');
  for (const item of entry.highlights) L.push(`- ${item}`);
  L.push('');
}

h('Things I built (`src/data/work.ts`)');
for (const project of d.work) {
  L.push(`### ${project.id} · ${project.title}`, '', project.description, '', `Tags: ${project.tags.join(', ')}`, '');
}

h('Play the work (`src/data/games.ts`)');
for (const game of d.games) {
  const kind = game.url ? 'fun-mode demo' : 'real-money title, demo on request';
  L.push(`- **${game.name}** (${game.type}, ${kind})${game.award ? ` · ${game.award}` : ''}: ${game.craft}`);
}

h('The stack (`src/data/expertise.ts`)');
for (const cell of d.bento) {
  L.push(`### ${cell.label}`);
  if (cell.title) L.push('', `**${cell.title}**`);
  if (cell.body) L.push('', cell.body);
  L.push('', cell.chips.join(' · '), '');
}

h('Contact (`src/data/contact.ts`)');
for (const detail of d.contactDetails) L.push(`- **${detail.label}:** ${detail.value}`);
L.push(`- **Elsewhere:** ${d.socials.map((social) => `${social.label} (${social.href})`).join(' · ')}`);

h('Copy that lives in components');
L.push(
  '- Hero role line and summary: `src/components/sections/Hero.tsx`',
  '- Profile lead and paragraphs: `src/components/sections/Profile.tsx`',
  '- Awards block: `src/components/sections/Awards.tsx`',
  '- Studio block ("I build the rush"): `src/components/sections/ExtraStudio.tsx`',
  '- CV files and facts: `src/components/sections/Resume.tsx`',
  '- Contact heading and closing band: `src/components/sections/Contact.tsx`',
  '- Page title, description and social tags: `index.html`',
  '',
);

writeFileSync('CONTENT.md', L.join('\n'));
console.log('CONTENT.md', L.length, 'lines');
